import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createRealtimeFake } from '../../../test/realtime'
import { createLiveStore } from './liveStore'
import { createRefreshQueue } from './refreshQueue'

beforeEach(() => { vi.useFakeTimers({ toFake: ['Date','setTimeout','clearTimeout','setInterval','clearInterval'] }) })
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks() })
describe('live resource scheduling', () => {
  it('coalesces bursts, scopes group jobs, and schedules one follow-up for events arriving during a read', async () => {
    const queue = createRefreshQueue()
    let finish!: () => void
    const board = vi.fn().mockImplementationOnce(() => new Promise<void>((resolve) => { finish = resolve })).mockResolvedValue(undefined)
    const other = vi.fn()
    queue.register('board', board, 'A'); queue.register('board', other, 'B')
    queue.start()
    for (let count = 0; count < 30; ++count) queue.invalidate(['board'], 'A')
    await vi.advanceTimersByTimeAsync(120)
    expect(board).toHaveBeenCalledOnce()
    expect(other).not.toHaveBeenCalled()
    queue.invalidate(['board'], 'A'); queue.invalidate(['board'], 'A')
    finish()
    await vi.advanceTimersByTimeAsync(120)
    expect(board).toHaveBeenCalledTimes(2)
    queue.stop()
  })
  it('cancels queued jobs when an account or resource disappears', async () => {
    const queue = createRefreshQueue()
    const fetch = vi.fn()
    const unregister = queue.register('discussion', fetch, 'A')
    queue.start(); queue.invalidate(); unregister()
    await vi.advanceTimersByTimeAsync(120)
    expect(fetch).not.toHaveBeenCalled()
    queue.register('board', fetch, 'A'); queue.invalidate(); queue.stop()
    await vi.advanceTimersByTimeAsync(120)
    expect(fetch).not.toHaveBeenCalled()
  })
})
describe('private live channel lifecycle', () => {
  it('waits for a previous account to finish closing a shared topic before the next account joins', async () => {
    const fake = createRealtimeFake()
    let finish!: () => void
    fake.removeChannel.mockImplementation(async (channel) => {
      if (channel.record.topic === 'northstar:group:shared') await new Promise<void>((resolve) => { finish = resolve })
      channel.record.stopped = true
      return 'ok'
    })
    const first = createLiveStore(fake.client, 'account-A')
    first.start(); first.selectGroup('shared')
    await vi.advanceTimersByTimeAsync(0)
    first.stop()
    const second = createLiveStore(fake.client, 'account-B')
    second.selectGroup('shared'); second.start()
    await vi.advanceTimersByTimeAsync(0)
    expect(fake.channel.mock.calls.filter(([topic]) => topic === 'northstar:group:shared')).toHaveLength(1)
    finish()
    await vi.advanceTimersByTimeAsync(0)
    expect(fake.channel.mock.calls.filter(([topic]) => topic === 'northstar:group:shared')).toHaveLength(2)
    expect(fake.channels.filter((row) => row.topic === 'northstar:group:shared' && !row.stopped)).toHaveLength(1)
    fake.removeChannel.mockResolvedValue('ok')
    second.stop()
    await vi.advanceTimersByTimeAsync(0)
  })
  it('joins only the identity and active group, then ignores messages from a previous group', async () => {
    const fake = createRealtimeFake()
    const store = createLiveStore(fake.client, 'user-A')
    const boardA = vi.fn(); const boardB = vi.fn()
    store.register('board', boardA, 'A'); store.register('board', boardB, 'B')
    store.start(); store.selectGroup('A')
    await vi.advanceTimersByTimeAsync(0)
    expect(fake.channel.mock.calls.map(([topic]) => topic)).toEqual(['northstar:account:user-A','northstar:group:A'])
    for (const [, config] of fake.channel.mock.calls) expect(config).toEqual({ config: { private: true } })
    const old = fake.channels.find((row) => row.topic === 'northstar:group:A')!
    store.selectGroup('B')
    await vi.advanceTimersByTimeAsync(0)
    old.message?.({ event: 'board', payload: {} })
    fake.emit('northstar:group:B','board')
    await vi.advanceTimersByTimeAsync(120)
    expect(boardA).not.toHaveBeenCalled()
    expect(boardB).toHaveBeenCalledOnce()
    expect(old.stopped).toBe(true)
    store.stop()
  })
  it('refetches after subscribing/reconnecting, reports failures, and periodically recovers missed notifications', async () => {
    const fake = createRealtimeFake()
    const store = createLiveStore(fake.client, 'user-A')
    const fetch = vi.fn()
    store.register('directory', fetch); store.start()
    await vi.advanceTimersByTimeAsync(0)
    fake.status('northstar:account:user-A','SUBSCRIBED')
    await vi.advanceTimersByTimeAsync(120)
    expect(store.getSnapshot().connection).toBe('live')
    expect(fetch).toHaveBeenCalledOnce()
    await vi.advanceTimersByTimeAsync(30_000)
    expect(fetch).toHaveBeenCalledTimes(2)
    fake.status('northstar:account:user-A','CHANNEL_ERROR')
    expect(store.getSnapshot().connection).toBe('paused')
    store.retry()
    await vi.advanceTimersByTimeAsync(0)
    fake.status('northstar:account:user-A','SUBSCRIBED')
    await vi.advanceTimersByTimeAsync(120)
    expect(store.getSnapshot().connection).toBe('live')
    expect(fetch).toHaveBeenCalledTimes(3)
    store.stop()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('cleans up StrictMode restarts without duplicate active subscriptions', async () => {
    const fake = createRealtimeFake()
    const store = createLiveStore(fake.client, 'user-A')
    store.start(); await vi.advanceTimersByTimeAsync(0)
    store.stop(); store.start()
    await vi.advanceTimersByTimeAsync(0)
    expect(fake.channels.filter((row) => !row.stopped)).toHaveLength(1)
    store.stop(); await vi.advanceTimersByTimeAsync(0)
    expect(fake.channels.filter((row) => !row.stopped)).toHaveLength(0)
  })
  it('pauses offline, catches up online, and drops callbacks after identity disposal', async () => {
    const fake = createRealtimeFake()
    const store = createLiveStore(fake.client, 'user-A')
    const fetch = vi.fn()
    store.register('directory', fetch); store.start()
    await vi.advanceTimersByTimeAsync(0)
    const old = fake.channels[0]
    vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(false)
    window.dispatchEvent(new Event('offline'))
    expect(store.getSnapshot().connection).toBe('offline')
    await vi.advanceTimersByTimeAsync(30_000)
    expect(fetch).not.toHaveBeenCalled()
    vi.spyOn(navigator, 'onLine', 'get').mockReturnValue(true)
    window.dispatchEvent(new Event('online'))
    await vi.advanceTimersByTimeAsync(120)
    expect(fetch).toHaveBeenCalledOnce()
    store.stop()
    old.message?.({ event: 'directory', payload: {} })
    window.dispatchEvent(new Event('focus'))
    await vi.advanceTimersByTimeAsync(120)
    expect(fetch).toHaveBeenCalledOnce()
  })
})

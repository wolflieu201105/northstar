# Compile the SQL Editor artifacts from immutable foundation + smaller modules.
# Does not connect to a database or run SQL.
# Once deployed, keep these migrations immutable; later database changes need
# new CLI-generated migrations and an updated compilation order.
$ErrorActionPreference = 'Stop'
$supabaseRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$foundationPath = Join-Path $supabaseRoot 'migrations\20261109072133_add_shared_group_foundation.sql'
$securityPath = Join-Path $supabaseRoot 'migrations\20261109075450_secure_shared_group_operations.sql'
$foundationText = [IO.File]::ReadAllText($foundationPath).Replace([string][char]13,'')
$marker = '-- Phase 12: clean shared-group foundation.'
$position = $foundationText.IndexOf($marker)
if ($position -lt 0 -or -not $foundationText.TrimEnd().EndsWith('commit;')) { throw 'Invalid foundation migration.' }
$foundationBody = $foundationText.Substring($position).TrimEnd()
$foundationBody = $foundationBody.Substring(0,$foundationBody.Length-7).TrimEnd()
$moduleNames = @('access.sql','activity.sql','groups.sql','tasks.sql','api.sql')
$modules = foreach ($moduleName in $moduleNames) {
  [IO.File]::ReadAllText((Join-Path $supabaseRoot "sql\groups\$moduleName")).Replace([string][char]13,'').Trim()
}
$newline = [string][char]10
$securityBody = '-- Phase 13: secure shared-group operations.' + $newline + ($modules -join ($newline+$newline))
$encoding = [Text.UTF8Encoding]::new($false)
[IO.File]::WriteAllText($securityPath, ('-- GENERATED by supabase/scripts/build-schema.ps1 from sql/groups/.'+$newline+'begin;'+$newline+$newline+$securityBody+$newline+$newline+"notify pgrst, 'reload schema';"+$newline+'commit;'+$newline),$encoding)
[IO.File]::WriteAllText((Join-Path $supabaseRoot 'schema.sql'), ('-- GENERATED clean installation: foundation plus Phase 13. Do not use over an existing schema.'+$newline+'begin;'+$newline+$newline+$foundationBody+$newline+$newline+$securityBody+$newline+$newline+"notify pgrst, 'reload schema';"+$newline+'commit;'+$newline),$encoding)
$resetBody = $foundationText.Trim()
if (-not $resetBody.StartsWith('begin;')) { throw 'Reset migration must begin a transaction.' }
$resetBody = $resetBody.Substring(6).Trim()
$resetBody = $resetBody.Substring(0,$resetBody.Length-7).Trim()
[IO.File]::WriteAllText((Join-Path $supabaseRoot 'reset.sql'), ('-- GENERATED DESTRUCTIVE reset + complete Phase 13 backend. Discards application data; retains Auth.'+$newline+'begin;'+$newline+$newline+$resetBody+$newline+$newline+$securityBody+$newline+$newline+"notify pgrst, 'reload schema';"+$newline+'commit;'+$newline),$encoding)
Write-Output 'Built clean schema, complete reset, and Phase 13 migration. No SQL executed.'
